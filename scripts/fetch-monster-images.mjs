#!/usr/bin/env node

/**
 * Downloads monster artwork into public/monster-images for local use.
 *
 * This is a human-triggered maintenance command, never part of the app, an
 * import, or CI. The images are not committed: the repository is public and
 * the artwork is not ours to redistribute, so every working copy fetches its
 * own. Swarfarm's static host is shared infrastructure, so the command
 * downloads one file at a time with a pause between requests, skips whatever
 * is already present, and stops rather than hammering a failing host.
 *
 *   npm run fetch:monster-images            # only what is still missing
 *   npm run fetch:monster-images -- --all   # ignore the resume, re-check all
 *   npm run fetch:monster-images -- --limit 200
 */
import { mkdir, readdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = resolve(repositoryRoot, 'app/data/swarfarm-monsters.json');
const imageDirectory = resolve(repositoryRoot, 'public/monster-images');
const allowlistPath = resolve(repositoryRoot, 'app/data/local-monster-images.ts');
const imageBaseUrl = 'https://swarfarm.com/static/herders/images/monsters/';
const minimumDelayMs = 250;
const maximumFailures = 10;
const requestTimeoutMs = 20_000;

const argv = process.argv.slice(2);
const refetchAll = argv.includes('--all');
const limitIndex = argv.indexOf('--limit');
const limit = limitIndex === -1 ? Infinity : Number(argv[limitIndex + 1]);

if (!Number.isFinite(limit) && limitIndex !== -1) {
  console.error('--limit needs a number, for example: --limit 200');
  process.exit(1);
}

function sleep(milliseconds) {
  return new Promise((resolvePromise) => setTimeout(resolvePromise, milliseconds));
}

/** The image filenames the catalog refers to, without duplicates. */
async function wantedFilenames() {
  const snapshot = JSON.parse(await readFile(snapshotPath, 'utf8'));
  if (!Array.isArray(snapshot.monsters)) throw new Error('The monster snapshot has no monsters array. Run npm run refresh:monsters first.');
  const names = snapshot.monsters
    .map((monster) => monster.image_filename)
    .filter((name) => typeof name === 'string' && /^[\w.-]+\.png$/.test(name));
  return [...new Set(names)].sort();
}

async function presentFilenames() {
  try {
    return new Set(await readdir(imageDirectory));
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return new Set();
    throw error;
  }
}

/**
 * Writes to a temporary name first so an interrupted run never leaves a
 * half-written PNG that a later run would treat as already downloaded.
 */
async function downloadImage(filename) {
  const response = await fetch(`${imageBaseUrl}${filename}`, {
    signal: AbortSignal.timeout(requestTimeoutMs),
    headers: { accept: 'image/png,image/*' },
  });
  if (response.status === 404) return 'missing';
  if (response.status === 429 || response.status >= 500) {
    const retryAfter = response.headers.get('retry-after');
    throw new Error(`Swarfarm answered ${response.status}${retryAfter ? ` and asked to wait ${retryAfter}s` : ''}. Stopping so the host is left alone; run the command again later.`);
  }
  if (!response.ok) throw new Error(`Swarfarm answered ${response.status} for ${filename}.`);

  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length < 100 || bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') return 'invalid';

  const target = resolve(imageDirectory, filename);
  const temporary = `${target}.partial`;
  await writeFile(temporary, bytes);
  await rename(temporary, target);
  return 'saved';
}

/**
 * The app only renders artwork listed here, so the allowlist is rewritten from
 * what is actually on disk after each run.
 */
async function writeAllowlist() {
  const files = (await readdir(imageDirectory))
    .filter((name) => name.endsWith('.png'))
    .sort();
  const entries = files.map((name) => `  '${name}',`).join('\n');
  const contents = `// Generated by scripts/fetch-monster-images.mjs — do not edit by hand.
//
// Swarfarm supplies image filenames in the monster catalog, but the artwork is
// not committed to this repository. Run \`npm run fetch:monster-images\` to
// download it locally. Only files that are actually present may be rendered,
// so a missing download degrades to the monster's initial instead of a broken
// image.
export const localMonsterImageFilenames = new Set([
${entries}
]);
`;
  await writeFile(allowlistPath, contents);
  return files.length;
}

async function main() {
  await mkdir(imageDirectory, { recursive: true });

  const wanted = await wantedFilenames();
  const present = await presentFilenames();
  const queue = (refetchAll ? wanted : wanted.filter((name) => !present.has(name))).slice(0, limit);

  console.log(`Catalog refers to ${wanted.length} images; ${present.size} already present.`);
  if (!queue.length) {
    const total = await writeAllowlist();
    console.log(`Nothing to download. The allowlist covers ${total} images.`);
    return;
  }
  console.log(`Downloading ${queue.length}, one at a time with a ${minimumDelayMs}ms pause. Ctrl+C is safe — a later run resumes.`);

  let saved = 0;
  let skipped = 0;
  const failures = [];

  for (const [index, filename] of queue.entries()) {
    if (refetchAll && present.has(filename)) { skipped += 1; continue; }
    try {
      const outcome = await downloadImage(filename);
      if (outcome === 'saved') saved += 1; else { skipped += 1; failures.push(`${filename} (${outcome})`); }
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      // A rate-limit or server error means the host wants to be left alone.
      if (message.includes('Stopping so the host is left alone')) {
        console.error(`\n${message}`);
        break;
      }
      failures.push(`${filename} (${message})`);
      if (failures.length >= maximumFailures) {
        console.error(`\nStopped after ${failures.length} failures. The images downloaded so far are kept.`);
        break;
      }
    }
    if ((index + 1) % 50 === 0 || index + 1 === queue.length) {
      console.log(`  ${index + 1}/${queue.length} · ${saved} saved`);
    }
    await sleep(minimumDelayMs);
  }

  const total = await writeAllowlist();
  console.log(`\nSaved ${saved} new images${skipped ? `, skipped ${skipped}` : ''}. The allowlist now covers ${total} of ${wanted.length}.`);
  if (failures.length) {
    console.log(`${failures.length} could not be downloaded:`);
    failures.slice(0, 10).forEach((entry) => console.log(`  ${entry}`));
    if (failures.length > 10) console.log(`  …and ${failures.length - 10} more.`);
  }
  if (total < wanted.length) console.log('Run the command again to pick up the rest.');
}

main().catch(async (error) => {
  console.error(error instanceof Error ? error.message : error);
  // Leave the allowlist consistent with whatever actually landed on disk.
  try { await writeAllowlist(); } catch { /* the original error matters more */ }
  process.exitCode = 1;
});
