#!/usr/bin/env node

/**
 * Downloads rune artwork into public/rune-images for local use.
 *
 * The same bargain as `fetch-monster-images.mjs`: a human-triggered maintenance
 * command, never part of the app, an import, or CI, and the files are never
 * committed because the game's artwork is not ours to redistribute. The game
 * draws a rune as two layers — a frame whose silhouette is the slot, and the
 * set's glyph on top of it — so that is what is fetched: six frames and one
 * glyph per set.
 *
 *   npm run fetch:rune-images           # only what is still missing
 *   npm run fetch:rune-images -- --all  # fetch every file again
 */
import { mkdir, readdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const setSourcePath = resolve(repositoryRoot, 'app/domain/runes/rune-sets.ts');
const imageDirectory = resolve(repositoryRoot, 'public/rune-images');
const allowlistPath = resolve(repositoryRoot, 'app/data/local-rune-images.ts');
const imageBaseUrl = 'https://swarfarm.com/static/herders/images/runes/';
const minimumDelayMs = 250;
const requestTimeoutMs = 20_000;
const refetchAll = process.argv.slice(2).includes('--all');

function sleep(milliseconds) {
  return new Promise((resolvePromise) => setTimeout(resolvePromise, milliseconds));
}

/**
 * The set names are read out of `rune-sets.ts` rather than restated here, so a
 * set added to the vocabulary is fetched by the next run without anyone having
 * to remember this list exists.
 */
async function wantedFilenames() {
  const source = await readFile(setSourcePath, 'utf8');
  const table = source.match(/const runeSetNames[^=]*=\s*\{([\s\S]*?)\};/);
  if (!table) throw new Error('Could not find runeSetNames in app/domain/runes/rune-sets.ts.');
  const sets = [...table[1].matchAll(/\d+:\s*'([^']+)'/g)].map((match) => `${match[1].toLowerCase()}.png`);
  if (sets.length === 0) throw new Error('runeSetNames in app/domain/runes/rune-sets.ts names no sets.');
  const frames = [1, 2, 3, 4, 5, 6].map((slot) => `rune${slot}.png`);
  return [...frames, ...sets];
}

async function presentFilenames() {
  try {
    return new Set(await readdir(imageDirectory));
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return new Set();
    throw error;
  }
}

/** Written under a temporary name first, so an interrupted run never leaves a
    half-written PNG that a later run would take for a finished one. */
async function downloadImage(filename) {
  const response = await fetch(`${imageBaseUrl}${filename}`, {
    signal: AbortSignal.timeout(requestTimeoutMs),
    headers: { accept: 'image/png,image/*' },
  });
  if (response.status === 404) return 'missing';
  if (response.status === 429 || response.status >= 500) {
    throw new Error(`Swarfarm answered ${response.status}. Stopping so the host is left alone; run the command again later.`);
  }
  if (!response.ok) throw new Error(`Swarfarm answered ${response.status} for ${filename}.`);

  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length < 100 || bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') return 'invalid';

  const target = resolve(imageDirectory, filename);
  const temporary = `${target}.partial`;
  await writeFile(temporary, bytes);
  await rename(temporary, target);
  return 'saved';
}

/** The app renders only artwork listed here, so the allowlist is rewritten from
    what is actually on disk after every run. */
async function writeAllowlist() {
  const files = (await readdir(imageDirectory)).filter((name) => name.endsWith('.png')).sort();
  const entries = files.map((name) => `  '${name}',`).join('\n');
  await writeFile(allowlistPath, `// Generated by scripts/fetch-rune-images.mjs — do not edit by hand.
//
// The rune artwork is not committed to this repository. Run
// \`npm run fetch:rune-images\` to download it locally. Only files that are
// actually present may be rendered, so a missing download degrades to a drawn
// placeholder instead of a broken image.
export const localRuneImageFilenames = new Set<string>([
${entries}
]);
`);
  return files.length;
}

async function main() {
  await mkdir(imageDirectory, { recursive: true });
  const wanted = await wantedFilenames();
  const present = await presentFilenames();
  const queue = refetchAll ? wanted : wanted.filter((name) => !present.has(name));

  console.log(`The rune vocabulary needs ${wanted.length} images; ${wanted.filter((name) => present.has(name)).length} already present.`);
  const failures = [];
  let saved = 0;
  for (const filename of queue) {
    const outcome = await downloadImage(filename);
    if (outcome === 'saved') saved += 1; else failures.push(`${filename} (${outcome})`);
    await sleep(minimumDelayMs);
  }

  const total = await writeAllowlist();
  console.log(`Saved ${saved} new images. The allowlist now covers ${total} of ${wanted.length}.`);
  if (failures.length) {
    console.log(`${failures.length} could not be downloaded:`);
    failures.forEach((entry) => console.log(`  ${entry}`));
  }
}

main().catch(async (error) => {
  console.error(error instanceof Error ? error.message : error);
  try { await writeAllowlist(); } catch { /* the original error matters more */ }
  process.exitCode = 1;
});
