#!/usr/bin/env node

/**
 * Downloads artifact artwork into public/artifact-images for local use.
 *
 * The same bargain as `fetch-rune-images.mjs`: a human-triggered maintenance
 * command, never part of the app, an import, or CI, and the files are never
 * committed because the game's artwork is not ours to redistribute. The game
 * draws an artifact as three layers — a ground in its grade's colour, the
 * slot's frame in that colour too (round for an attribute artifact, pointed for
 * a type artifact), and the element's or type's symbol on top — so that is what
 * is fetched: a ground and two frames per grade, and one symbol per element and
 * per type.
 *
 *   npm run fetch:artifact-images           # only what is still missing
 *   npm run fetch:artifact-images -- --all  # fetch every file again
 */
import { mkdir, readdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const propertiesPath = resolve(repositoryRoot, 'app/domain/artifacts/artifact-properties.ts');
const tiersPath = resolve(repositoryRoot, 'app/domain/shared/quality-tiers.ts');
const imageDirectory = resolve(repositoryRoot, 'public/artifact-images');
const allowlistPath = resolve(repositoryRoot, 'app/data/local-artifact-images.ts');
const imageBaseUrl = 'https://swarfarm.com/static/herders/images/artifacts/';
const minimumDelayMs = 250;
const requestTimeoutMs = 20_000;
const refetchAll = process.argv.slice(2).includes('--all');

function sleep(milliseconds) {
  return new Promise((resolvePromise) => setTimeout(resolvePromise, milliseconds));
}

/* Read out of the vocabulary rather than restated here, so a grade, element or
   type added there is fetched by the next run. */
function namesIn(source, pattern, what) {
  const table = source.match(pattern);
  if (!table) throw new Error(`Could not find ${what}.`);
  const names = [...table[1].matchAll(/'([^']+)'/g)].map((match) => match[1].toLowerCase());
  if (names.length === 0) throw new Error(`${what} names nothing.`);
  return names;
}

async function wantedFilenames() {
  const properties = await readFile(propertiesPath, 'utf8');
  const tiers = await readFile(tiersPath, 'utf8');
  const grades = namesIn(tiers, /qualityTiers\s*=\s*\[([^\]]*)\]/, 'qualityTiers in app/domain/shared/quality-tiers.ts');
  const elements = namesIn(properties, /artifactElements[^=]*=\s*\{([^}]*)\}/, 'artifactElements in app/domain/artifacts/artifact-properties.ts');
  const archetypes = namesIn(properties, /artifactArchetypes[^=]*=\s*\{([^}]*)\}/, 'artifactArchetypes in app/domain/artifacts/artifact-properties.ts');
  const layers = grades.flatMap((grade) => [`bg_${grade}.png`, `element_${grade}.png`, `archetype_${grade}.png`]);
  return [...layers, ...[...elements, ...archetypes].map((name) => `${name}.png`)];
}

async function presentFilenames() {
  try {
    return new Set(await readdir(imageDirectory));
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return new Set();
    throw error;
  }
}

/** Written under a temporary name first, so an interrupted run never leaves a
    half-written PNG that a later run would take for a finished one. */
async function downloadImage(filename) {
  const response = await fetch(`${imageBaseUrl}${filename}`, {
    signal: AbortSignal.timeout(requestTimeoutMs),
    headers: { accept: 'image/png,image/*' },
  });
  if (response.status === 404) return 'missing';
  if (response.status === 429 || response.status >= 500) {
    throw new Error(`Swarfarm answered ${response.status}. Stopping so the host is left alone; run the command again later.`);
  }
  if (!response.ok) throw new Error(`Swarfarm answered ${response.status} for ${filename}.`);

  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length < 100 || bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') return 'invalid';

  const target = resolve(imageDirectory, filename);
  const temporary = `${target}.partial`;
  await writeFile(temporary, bytes);
  await rename(temporary, target);
  return 'saved';
}

/** The app renders only artwork listed here, so the allowlist is rewritten from
    what is actually on disk after every run. */
async function writeAllowlist() {
  const files = (await readdir(imageDirectory)).filter((name) => name.endsWith('.png')).sort();
  const entries = files.map((name) => `  '${name}',`).join('\n');
  await writeFile(allowlistPath, `// Generated by scripts/fetch-artifact-images.mjs — do not edit by hand.
//
// The artifact artwork is not committed to this repository. Run
// \`npm run fetch:artifact-images\` to download it locally. Only files that are
// actually present may be rendered, so a missing download degrades to a drawn
// mark instead of a broken image.
export const localArtifactImageFilenames = new Set<string>([
${entries}
]);
`);
  return files.length;
}

async function main() {
  await mkdir(imageDirectory, { recursive: true });
  const wanted = await wantedFilenames();
  const present = await presentFilenames();
  const queue = refetchAll ? wanted : wanted.filter((name) => !present.has(name));

  console.log(`The artifact vocabulary needs ${wanted.length} images; ${wanted.filter((name) => present.has(name)).length} already present.`);
  const failures = [];
  let saved = 0;
  for (const filename of queue) {
    const outcome = await downloadImage(filename);
    if (outcome === 'saved') saved += 1; else failures.push(`${filename} (${outcome})`);
    await sleep(minimumDelayMs);
  }

  const total = await writeAllowlist();
  console.log(`Saved ${saved} new images. The allowlist now covers ${total} of ${wanted.length}.`);
  if (failures.length) {
    console.log(`${failures.length} could not be downloaded:`);
    failures.forEach((entry) => console.log(`  ${entry}`));
  }
}

main().catch(async (error) => {
  console.error(error instanceof Error ? error.message : error);
  try { await writeAllowlist(); } catch { /* the original error matters more */ }
  process.exitCode = 1;
});
